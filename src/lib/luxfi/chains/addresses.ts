import { SupportedChainId } from './chains'

type AddressMap = { [chainId: number]: string }

// Helper to construct same address across multiple chains
function constructSameAddressMap(address: string, additionalChains: SupportedChainId[] = []): AddressMap {
  return [
    SupportedChainId.MAINNET,
    SupportedChainId.ROPSTEN,
    SupportedChainId.RINKEBY,
    SupportedChainId.GOERLI,
    SupportedChainId.KOVAN,
    ...additionalChains,
  ].reduce<AddressMap>((memo, chainId) => {
    memo[chainId] = address
    return memo
  }, {})
}

